/**
 * One Material symbol, filling the view's shorter side, in one colour.
 * 一個 Material 符號，填滿 view 較短的一邊，單一顏色。
 */
class MaterialSymbolView(context: Context) : View(context) {
    private var outline: Path? = null
    private val drawn = Path()
    private val paint = Paint(Paint.ANTI_ALIAS_FLAG)
    private val matrix = Matrix()

    /** Returns false when there is no symbol of that name. 沒有該名稱的符號時回傳 false。 */
    fun setSymbol(name: String): Boolean {
        outline = MaterialSymbols.path(name)
        invalidate()
        return outline != null
    }

    fun setColor(color: Int) {
        paint.color = color
        invalidate()
    }

    override fun onDraw(canvas: Canvas) {
        super.onDraw(canvas)
        val source = outline ?: return
        val side = minOf(width, height).toFloat()
        matrix.reset()
        matrix.setScale(side / 960f, side / 960f)
        matrix.preTranslate(0f, 960f)
        matrix.postTranslate((width - side) / 2, (height - side) / 2)
        source.transform(matrix, drawn)
        canvas.drawPath(drawn, paint)
    }
}
